/* Guided experience only. Signature generation remains in app.js. */
(function () {
 "use strict";
 const $ = id => document.getElementById(id);
 let stage = 1;
 const steps = [...document.querySelectorAll(".progress-step")];
 const panels = [...document.querySelectorAll(".step-panel")];
 const stepError = $("stepError");
 const fieldIds = ["name", "email", "website", "orcid"];

 function markInvalid(field, value) {
  if(!field)return;
  if(value)field.setAttribute("aria-invalid","true");
  else field.removeAttribute("aria-invalid");
 }
 function clearErrors() {
  stepError.textContent = "";
  fieldIds.forEach(id => markInvalid($(id),false));
 }
 function checkDetails(focus = true) {
  clearErrors();
  const warning = window.SPSS_QA?.staffValid?.() || "";
  if(!warning)return true;
  let field = $("name");
  if(/email/i.test(warning))field = $("email");
  else if(/profile|https/i.test(warning))field = $("website");
  else if(/orcid/i.test(warning))field = $("orcid");
  markInvalid(field,true);
  stepError.textContent = warning;
  if(focus)field?.focus();
  return false;
 }
 function showStage(next, opts = {}) {
  if(![1,2,3].includes(next))return;
  // Going backwards never discards inputs. Entering a later stage requires
  // mandatory details, including any supplied optional URLs/ORCID.
  if(next>1 && !checkDetails(true)) {
   next=1;
   if(stage===1) return;
  }
  stage=next;
  panels.forEach(p => {p.hidden=Number(p.dataset.panel)!==next;});
  steps.forEach(button => {
   const number=Number(button.dataset.step);
   button.classList.toggle("active",number===next);
   button.classList.toggle("complete",number<next);
   if(number===next)button.setAttribute("aria-current","step");
   else button.removeAttribute("aria-current");
   button.querySelector(".number").textContent=number<next?"✓":String(number);
  });
  const title=document.querySelector('[data-panel="'+next+'"] h2');
  if(opts.focusTitle){
   title.setAttribute("tabindex","-1");
   title.focus({preventScroll:true});
  }
  if(next===3){
   $("selectionFeedback").textContent="";
  }
  if(opts.scroll!==false && matchMedia("(max-width:1080px)").matches) {
   document.querySelector(".progress-nav").scrollIntoView({behavior:"smooth",block:"start"});
  }
 }
 steps.forEach(b => b.addEventListener("click",()=>showStage(Number(b.dataset.step),{focusTitle:true})));
 $("goPersonalise").addEventListener("click",()=>showStage(2,{focusTitle:true}));
 $("goReady").addEventListener("click",()=>showStage(3,{focusTitle:true}));
 $("backToDetails").addEventListener("click",()=>showStage(1,{focusTitle:true}));
 $("backToPersonalise").addEventListener("click",()=>showStage(2,{focusTitle:true}));
 $("backToDetailsFromFinish").addEventListener("click",()=>showStage(1,{focusTitle:true}));

 fieldIds.forEach(id=>$(id)?.addEventListener("input",()=>{
  if(stepError.textContent) {
   clearErrors();
  }
 }));
 function feedback(group) {
  const el=$(group);
  el.addEventListener("click",event=>{
   const b=event.target.closest('button');
   if(!b || b.disabled)return;
   const previouslySelected=b.getAttribute("aria-pressed")==="true";
   if(group==="claimGrid" && !previouslySelected && !window.SPSS_QA.selectedClaims().includes(b.dataset.claimId)){
    $("selectionFeedback").textContent="You can select up to three claims. Remove one before adding another.";
    return;
   }
   $("selectionFeedback").textContent=previouslySelected?
    "Removed from your signature." : "Added to your signature.";
  });
 }
 feedback("logoGrid");
 feedback("claimGrid");

 // Copy and download handlers run in app.js; observe their actual status,
 // rather than claiming clipboard success from this presentation layer.
 const status=$("status");
 const observer=new MutationObserver(()=>{
  const msg=status.textContent||"";
  if(msg && /copied/i.test(msg))$("installHelp").open=true;
 });
 observer.observe(status,{childList:true,characterData:true,subtree:true});

 // The branded preview frame is interface-only. Outlook receives the exact
 // HTML generated by the existing signature() function.
 window.SPSS_STUDIO={showStage:step=>showStage(step,{scroll:false}),currentStage:()=>stage};
})();
